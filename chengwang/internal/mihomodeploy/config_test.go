func labConfigTestBuild(t *testing.T, spec LabConfigSpec) *LabConfigArtifact {
	t.Helper()
	artifact, err := BuildLabConfig(spec)
	if err != nil || artifact == nil {
		t.Fatal("laboratory fixture failed construction")
	}
	return artifact
}
func labConfigTestMap(t *testing.T, artifact *LabConfigArtifact) map[string]any {
	t.Helper()
	var value map[string]any
	if yaml.Unmarshal(artifact.Bytes(), &value) != nil {
		t.Fatal("generated bytes failed YAML decoding")
	}
	return value
}
func labConfigTestRejected(t *testing.T, spec LabConfigSpec, code LabConfigCode) {
	t.Helper()
	artifact, err := BuildLabConfig(spec)
	var typed *LabConfigError
	if artifact != nil || !errors.As(err, &typed) || typed.Code != code || len(typed.Blockers()) == 0 {
		t.Fatal("expected closed typed rejection")
	}
	if strings.Contains(fmt.Sprintf("%v %#v", err, err), spec.ControllerSecret) {
		t.Fatal("private secret escaped typed error")
	}
}

func TestLabConfigCompleteStaticListenersAndDisabledSurfaces(t *testing.T) {
	spec := labConfigTestSpec()
	artifact := labConfigTestBuild(t, spec)
	value := labConfigTestMap(t, artifact)
	for key, want := range map[string]any{"mixed-port": int(spec.MixedPort), "external-controller": "127.0.0.1:19090", "bind-address": "127.0.0.1", "mode": "rule", "allow-lan": false, "ipv6": false,
		"port": 0, "socks-port": 0, "redir-port": 0, "tproxy-port": 0, "geo-auto-update": false, "geodata-mode": false, "external-ui": "", "external-ui-url": "", "external-controller-unix": "", "external-controller-pipe": "", "external-controller-tls": "", "find-process-mode": "off"} {
		if !reflect.DeepEqual(value[key], want) {
			t.Fatal("fixed laboratory boundary differs")
		}
	}
	if value["secret"] != spec.ControllerSecret {
		t.Fatal("private controller authentication missing")
	}
	for _, key := range []string{"tun", "ntp", "sniffer"} {
		if value[key].(map[string]any)["enable"] != false {
			t.Fatal("unexpected enabled network surface")
		}
	}
	dns := value["dns"].(map[string]any)
	if dns["enable"] != false || dns["listen"] != "" || dns["ipv6"] != false || !reflect.DeepEqual(dns["default-nameserver"], []any{"127.0.0.1:1"}) || len(dns["fallback"].([]any)) != 0 {
		t.Fatal("built-in DNS boundary differs")
	}
	for _, key := range []string{"proxy-providers", "rule-providers", "listeners", "tunnels"} {
		if _, exists := value[key]; exists {
			t.Fatal("unapproved external feature emitted")
		}
	}
	for _, url := range value["geox-url"].(map[string]any) {
		if url != "" {
			t.Fatal("external geography URL emitted")
		}
	}
	if artifact.AdmissionError() != nil || !artifact.Descriptor().Admissible {
		t.Fatal("static-only laboratory artifact not eligible")
	}
}

