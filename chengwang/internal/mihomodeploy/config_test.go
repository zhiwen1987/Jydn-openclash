func TestLabConfigRawAndMetadataAreOwnedAndSecretSafe(t *testing.T) {
	spec := labConfigTestSpec()
	artifact := labConfigTestBuild(t, spec)
	before := artifact.Bytes()
	raw := artifact.Bytes()
	raw[0] ^= 1
	if !bytes.Equal(before, artifact.Bytes()) {
		t.Fatal("private bytes aliased")
	}
	meta := artifact.Descriptor()
	meta.Capabilities[0] = "changed"
	meta.Requirements = append(meta.Requirements, LabPolicyRequirement{Kind: "changed"})
	meta.Blockers = append(meta.Blockers, LabConfigBlocker{Code: LabConfigInvalid})
	if !artifact.Descriptor().Admissible || artifact.Descriptor().Capabilities[0] == "changed" || len(artifact.Descriptor().Requirements) != 0 || len(artifact.Descriptor().Blockers) != 0 {
		t.Fatal("metadata aliased")
	}
	wantJSON, err := json.Marshal(artifact.Descriptor())
	if err != nil {
		t.Fatal("metadata encoding failed")
	}
	valueCopy := *artifact
	for _, item := range []struct {
		name, verb string
		value      any
	}{
		{"pointer_plain", "%v", artifact}, {"pointer_plus", "%+v", artifact}, {"pointer_sharp", "%#v", artifact}, {"pointer_hex", "%x", artifact},
		{"value_plain", "%v", valueCopy}, {"value_plus", "%+v", valueCopy}, {"value_sharp", "%#v", valueCopy}, {"value_hex", "%x", valueCopy},
	} {
		t.Run(item.name, func(t *testing.T) {
			want := string(wantJSON)
			if item.verb == "%x" {
				want = hex.EncodeToString(wantJSON)
			}
			if fmt.Sprintf(item.verb, item.value) != want {
				t.Fatal("formatter exposed a non-metadata representation")
			}
		})
	}
	for _, item := range []any{artifact, valueCopy} {
		encoded, marshalErr := json.Marshal(item)
		if marshalErr != nil || !bytes.Equal(encoded, wantJSON) {
			t.Fatal("pointer or value JSON exposed non-metadata content")
		}
	}
	for _, view := range []any{artifact, valueCopy, &valueCopy} {
		for _, verb := range []string{"%p", "%d", "%T", "%w", "%x", "%#v"} {
			text := fmt.Sprintf(verb, view)
			for _, needle := range []string{spec.ControllerSecret, string(before), fmt.Sprint(before), hex.EncodeToString([]byte(spec.ControllerSecret))} {
				if strings.Contains(text, needle) {
					t.Fatal("unsupported formatting exposed private artifact fields")
				}
			}
		}
	}
	zero := LabConfigArtifact{}
	if zero.Bytes() != nil || zero.AdmissionError() == nil || zero.Descriptor().Admissible {
		t.Fatal("opaque zero artifact became usable")
	}
	var nilArtifact *LabConfigArtifact
	for _, verb := range []string{"%v", "%+v", "%#v", "%x"} {
		if fmt.Sprintf(verb, nilArtifact) != "<nil>" {
			t.Fatal("nil formatter did not fail closed")
		}
	}
	if encoded, marshalErr := json.Marshal(nilArtifact); marshalErr != nil || string(encoded) != "null" {
		t.Fatal("nil JSON did not remain null")
	}
	for _, text := range []string{string(wantJSON), fmt.Sprintf("%v %#v", spec, spec)} {
		if strings.Contains(text, spec.ControllerSecret) || strings.Contains(text, "mixed-port:") || strings.Contains(text, "node-a") {
			t.Fatal("private input leaked to public metadata")
		}
	}
	specJSON, _ := json.Marshal(spec)
	if strings.Contains(string(specJSON), spec.ControllerSecret) {
		t.Fatal("specification secret escaped")
	}
	spec.Draft.Pools[0].Members[0] = "mutated"
	spec.HTTPNodes[0].ID = "mutated"
	if !bytes.Equal(before, artifact.Bytes()) {
		t.Fatal("caller input retained")
	}
	if artifact.Descriptor().SHA256 != labConfigHash(before) || artifact.Descriptor().Bytes != len(before) {
		t.Fatal("artifact content binding invalid")
	}
}

