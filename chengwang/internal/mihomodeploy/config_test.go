func TestLabConfigExternalControllerRequirementsBlockAdmission(t *testing.T) {
	cases := []struct {
		kind   string
		change func(*LabConfigSpec)
	}{
		{"fallback_policy", func(s *LabConfigSpec) { s.Draft.Businesses[0].Fallback = "DIRECT" }},
		{"skip_empty_pool_policy", func(s *LabConfigSpec) { s.Draft.Businesses[0].SkipEmptyPools = true }},
		{"failure_threshold_policy", func(s *LabConfigSpec) { s.Draft.Businesses[0].FailuresToSwitch = 3 }},
		{"probe_schedule_policy", func(s *LabConfigSpec) { s.Draft.Businesses[0].ProbeIntervalSec = 30 }},
		{"session_stickiness_policy", func(s *LabConfigSpec) { s.Draft.Businesses[0].SessionStickyMin = 30 }},
		{"switch_cooldown_policy", func(s *LabConfigSpec) { s.Draft.Businesses[0].SwitchCooldownSec = 300 }},
		{"capability_eligibility", func(s *LabConfigSpec) { s.Draft.Businesses[0].RequireCapabilities = []string{"chatgpt"} }},
		{"capability_eligibility", func(s *LabConfigSpec) { s.Draft.Pools[0].Capabilities = []string{"chatgpt"} }},
	}
	for _, item := range cases {
		spec := labConfigTestSpec()
		item.change(&spec)
		before, _ := json.Marshal(spec.Draft)
		artifact := labConfigTestBuild(t, spec)
		meta := artifact.Descriptor()
		if meta.Admissible || len(meta.Requirements) != 1 || meta.Requirements[0].Kind != item.kind || len(meta.Blockers) != 1 || meta.Blockers[0].Code != LabConfigExternalRequirements {
			t.Fatal("unmet controller obligation admitted")
		}
		var typed *LabConfigError
		if !errors.As(artifact.AdmissionError(), &typed) || typed.Code != LabConfigExternalRequirements {
			t.Fatal("missing execution fence")
		}
		after, _ := json.Marshal(spec.Draft)
		if !bytes.Equal(before, after) {
			t.Fatal("original policy mutated")
		}
		meta.Requirements[0].Kind = "changed"
		meta.Blockers[0].Code = LabConfigInvalid
		if artifact.Descriptor().Requirements[0].Kind != item.kind || artifact.Descriptor().Blockers[0].Code != LabConfigExternalRequirements {
			t.Fatal("obligation metadata aliased")
		}
	}
}

