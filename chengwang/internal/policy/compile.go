package policy

import (
	"bytes"
	"fmt"
	"sort"
	"strings"

	"chengwang/internal/domain"
)

// CompileMihomo creates a deterministic, reviewable compatibility artifact.
// It is intentionally not a complete runnable config: device-specific adapters
// must merge it with listeners, DNS credentials and proxy-provider sources.
func CompileMihomo(draft domain.PolicyDraft) ([]byte, error) {
	result := Validate(draft)
	if !result.Valid {
		return nil, fmt.Errorf("draft failed validation")
	}
	var out bytes.Buffer
	out.WriteString("# Generated by Chengwang. Review before deployment.\n")
	out.WriteString("proxy-groups:\n")
	pools := append([]domain.NodePool(nil), draft.Pools...)
	sort.Slice(pools, func(i, j int) bool { return pools[i].ID < pools[j].ID })
	for _, pool := range pools {
		fmt.Fprintf(&out, "  - name: %s\n    type: select\n    proxies:\n", yamlScalar(pool.ID))
		for _, member := range pool.Members {
			fmt.Fprintf(&out, "      - %s\n", yamlScalar(member))
		}
	}
	out.WriteString("rules:\n")
	for _, business := range draft.Businesses {
		target := business.Strategy
		if !builtin(target) {
			target = business.Strategy
		}
		for _, domainName := range business.Domains {
			fmt.Fprintf(&out, "  - DOMAIN-SUFFIX,%s,%s\n", strings.TrimPrefix(domainName, "+."), target)
		}
	}
	out.WriteString("  - MATCH,默认策略\n")
	return out.Bytes(), nil
}

func yamlScalar(value string) string {
	return `"` + strings.ReplaceAll(strings.ReplaceAll(value, `\`, `\\`), `"`, `\"`) + `"`
}
